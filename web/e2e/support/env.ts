// What the global setup hands to the tests, through environment variables (the test workers inherit them), and the
// made-up instance the tests set up.

import { readFileSync } from 'node:fs'
import type { ArchiveSpec } from './archive.ts'

/** The port the binary listens on; chosen in playwright.config.ts, before the workers start. */
export const portVariable = 'OSFM_E2E_PORT'
/** The setup code, read from the server log by the global setup. */
export const setupCodeVariable = 'OSFM_E2E_SETUP_CODE'
/** The instance's data directory, created by the global setup. */
export const dataDirVariable = 'OSFM_E2E_DATA_DIR'

/**
 * The address the tests open: localhost, not 127.0.0.1, because the passkey relying party of a local instance is
 * localhost (docs/architecture.md §3.3). The binary listens on 127.0.0.1 only.
 */
export function baseURL(): string {
  const port = process.env[portVariable]
  if (!port) {
    throw new Error(`${portVariable} is not set: run the tests through playwright.config.ts`)
  }
  return `http://localhost:${port}`
}

export function setupCode(): string {
  const code = process.env[setupCodeVariable]
  if (!code) {
    throw new Error(`${setupCodeVariable} is not set: the global setup did not run`)
  }
  return code
}

export function dataDir(): string {
  const dir = process.env[dataDirVariable]
  if (!dir) {
    throw new Error(`${dataDirVariable} is not set: the global setup did not run`)
  }
  return dir
}

